import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {randomUUID} from 'node:crypto';
import {mkdir, readFile, writeFile} from 'node:fs/promises';
import {chromium} from 'playwright';
import {harness, until} from './harness.mjs';
import {embeddingProvider} from './embedding-provider.mjs';

const directory = '.local/checks/maintenance-browser';
await mkdir(directory, {recursive: true});
const embedding = await embeddingProvider();
let calls = 0;
const prefill = createServer(async (req, res) => {
  let raw = ''; for await (const chunk of req) raw += chunk;
  const request = JSON.parse(raw), input = JSON.parse(request.messages[1].content);
  const source = input.sources.find(item => item.complete && item.body.length);
  const result = {entries: input.object.entries.map(entry => ({entry_id: entry.entry_id, value: '来自合成来源的待核对说明', gaps: ['本地协议试用不证明业务正确性'], evidence: [{source_id: source.source_id, version: source.version, location: '合成来源', quote: source.body.slice(0, 80)}]}))};
  calls++;
  res.writeHead(200, {'content-type': 'application/json'});
  res.end(JSON.stringify({choices: [{finish_reason: 'tool_calls', message: {tool_calls: [{type: 'function', function: {name: 'submit_semantic_prefill', arguments: JSON.stringify(result)}}]}}], usage: {prompt_tokens: 100, completion_tokens: 80}}));
});
await new Promise(resolve => prefill.listen(0, '127.0.0.1', resolve));
const collection = 'da_ui_' + randomUUID().replaceAll('-', '');
const profile = {provider_id: 'deepseek', model_id: 'deepseek-flash', trial_id: randomUUID(), price_version: '2026-10-04-peak-usd', input_limit: 32768, output_limit: 2048, trial_call_limit: 100, trial_cost_micros: '300000', request_call_limit: 9, toolset: 'data', payload_bytes_limit: 65536};
const h = await harness({web: true, env: {...embedding.env, DATA_AGENT_VECTOR_URL: 'http://127.0.0.1:19531', DATA_AGENT_VECTOR_COLLECTION: collection, DATA_AGENT_VECTOR_TOKEN_FILE: process.cwd() + '/.local/infra/milvus-root-password', DATA_AGENT_PREFILL_TEST: '1', DATA_AGENT_PREFILL_PROFILE: JSON.stringify(profile), DATA_AGENT_PREFILL_URL: 'http://127.0.0.1:' + prefill.address().port}});
const browser = await chromium.launch();
const page = await browser.newPage({viewport: {width: 1440, height: 1000}});
const checks = [], errors = [];
page.on('pageerror', error => errors.push(error.message));
let passed = false;
const read = async () => (await h.request('/knowledge/table-demo_order_detail')).value;
const indexed = async () => {
  const result = await h.request('/knowledge?q=demo_order_detail');
  return result.value.search_coverage?.index_state === 'current' && result.value.search_coverage.vector_state === 'available';
};
try {
  await until(indexed, '初始索引可用', 120000);
  await page.goto(h.url);
  await page.getByLabel('演示登录凭据').fill(h.tokens.alice);
  await page.getByRole('button', {name: '进入工作台 →'}).click();
  await page.getByRole('button', {name: '语义管理', exact: true}).click();
  await page.getByRole('navigation', {name: '语义对象'}).getByRole('button', {name: /^demo_order_detail /}).click();
  const entry = page.locator('.semantic-entry').first();
  await entry.getByRole('button', {name: '编辑', exact: true}).click();
  await entry.locator('textarea').fill('人工确认：保留这一份业务定义。');
  await entry.getByRole('button', {name: '保存修改', exact: true}).click();
  await until(async () => (await read()).entries[0].effective_value === '人工确认：保留这一份业务定义。', '人工定义保存');
  await page.getByRole('button', {name: '重新预填', exact: true}).click();
  await until(async () => (await read()).prefill_status?.state === 'succeeded', '分析与复核完成', 60000);
  const analyzed = await read();
  assert.equal(analyzed.entries[0].effective_value, '人工确认：保留这一份业务定义。');
  assert.equal(analyzed.entries[0].suggestion.value, '来自合成来源的待核对说明');
  assert.equal(analyzed.entries[0].human_override.edited_by, 'alice');
  await entry.getByText('人工确认：保留这一份业务定义。', {exact: true}).waitFor();
  checks.push('真实页面重新预填成功，模型建议与人工值分开保存，人工有效值仍显示');
  await until(indexed, '预填后的当前版本入索引', 120000);
  await page.getByText('维护操作', {exact: true}).click();
  await page.getByRole('button', {name: '重建检索索引', exact: true}).click();
  await page.getByText('索引重建已排队。检索期间仍会核对当前正式知识，覆盖情况会随进度更新。', {exact: true}).waitFor();
  await until(indexed, '用户发起索引重建完成', 120000);
  const rebuilt = await read();
  assert.equal(rebuilt.version, analyzed.version);
  assert.equal(rebuilt.entries[0].effective_value, analyzed.entries[0].effective_value);
  assert.ok(embedding.requests.length > 0);
  assert.ok(calls >= 2);
  checks.push('真实页面重建索引成功，检索恢复当前覆盖，重建不改语义版本或人工正文');
  assert.deepEqual(errors, []);
  await page.screenshot({path: directory + '/completed.png', fullPage: true});
  passed = true;
} finally {
  if (!passed) await page.screenshot({path: directory + '/failure.png', fullPage: true}).catch(() => {});
  await writeFile(directory + '/report.json', JSON.stringify({passed, checks, errors, prefillProtocolRequests: calls, embeddingProtocolRequests: embedding.requests.length, officialRequests: 0, environment: 'isolated MySQL and Milvus collection; local protocol providers'}, null, 2));
  await browser.close(); await h.close();
  const token = (await readFile('.local/infra/milvus-root-password', 'utf8')).trim();
  const dropped = await fetch('http://127.0.0.1:19531/v2/vectordb/collections/drop', {method: 'POST', headers: {'content-type': 'application/json', authorization: 'Bearer root:' + token}, body: JSON.stringify({dbName: 'default', collectionName: collection})}).then(response => response.json());
  assert.equal(dropped.code, 0);
  await embedding.close(); prefill.closeAllConnections(); await new Promise(resolve => prefill.close(resolve));
  console.log(JSON.stringify({passed, checks, errors, officialRequests: 0}));
}
