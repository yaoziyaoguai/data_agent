import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {mkdir, readFile, writeFile} from 'node:fs/promises';
import {randomUUID} from 'node:crypto';

const directory='.local/checks/business-conversation-'+randomUUID();
await mkdir(directory,{recursive:true});
const output=directory+'/result.json';
const run=spawnSync(process.execPath,['tests/mvp/run-business-acceptance.mjs','--check',
  '--interaction','conversation','--cases','S02','--output',output],{encoding:'utf8',timeout:300000,maxBuffer:8*1024*1024});
await writeFile(directory+'/runner.log',(run.stdout??'')+(run.stderr??''));
assert.equal(run.signal,null,'代表检查须完成并清理本次harness');
assert.equal(run.status,0,'runner失败，详见 '+directory+'/runner.log');
const report=JSON.parse(await readFile(output,'utf8'));
assert.equal(report.interaction,'conversation','新模式须走自然聊天授权，不可忽略参数落回按钮链');
assert.equal(report.machinePassed,true);
assert.equal(report.officialRequests,0);
assert.deepEqual(report.selectedCases,['S02']);
assert.equal(report.pending.length,15,'单代表不能覆盖默认16题的分母');
const sample=report.checks[0].artifacts;
assert.equal(sample.originalQuestion,'查2026年1月整月支付客户数，保留未知客户边界。请先给出SQL草稿，等待我明确要求执行；此时不要提交查询。');
assert.equal(sample.draftSubmits,0);
assert.equal(sample.authorization.message,sample.execution.message_id);
assert.equal(sample.authorization.budget,sample.execution.budget_scope_id);
assert.equal(sample.authorization.attempts,1);
assert.equal(sample.wake.budget_scope_id,sample.execution.budget_scope_id);
assert.equal(sample.platformSubmits.length,1,'数平台实际HTTP派发，不只数去重后的记录');
assert.equal(sample.platformSubmits[0].payload.query_id,sample.query.id);
assert.deepEqual(sample.result.rows.map(row=>row.map(Number)),sample.independent.expected_rows);
assert.equal(sample.finalOutput.refreshMatches,true);
assert.equal(sample.finalOutput.streamMatches,true);
assert.equal(report.browser.passed,true);
assert.equal(report.browser.refreshMatches,true);
assert.equal(report.browser.conversation_id,sample.cid);
assert.equal(report.browser.query_id,sample.query.id);
assert.equal(report.browser.same_title_history_count,2,'旧S02题名的历史夹具与新对话都保留');
assert.equal(report.browser.previous_history_retained,true);
assert.notEqual(sample.previousHistory.conversation_id,sample.cid);
assert.equal(report.ledgerDelta.reserved_micros,0);
assert.equal(report.modelDispatches,report.ledgerDelta.calls);
console.log(JSON.stringify({passed:true,officialRequests:0,evidence:output,browser:report.browser.passed}));
