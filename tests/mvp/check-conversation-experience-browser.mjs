import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {mkdir, writeFile} from 'node:fs/promises';
import {chromium} from 'playwright';
import {harness, until} from './harness.mjs';
const h=await harness({web:true,env:{DATA_AGENT_QUERY_DELAY_SECONDS:'4'}});
const browser=await chromium.launch();
const context=await browser.newContext({viewport:{width:1440,height:1000},permissions:['clipboard-read','clipboard-write']});
const page=await context.newPage();
const directory='.local/checks/conversation-experience';await mkdir(directory,{recursive:true});
const checks=[],errors=[];let passed=false;page.on('pageerror',e=>errors.push(e.message));
const list=async cid=>(await h.request('/conversations/'+cid+'/queries')).value;
const send=async text=>{await page.getByLabel('你的数据问题').fill(text);await page.getByRole('button',{name:'发送 ↑',exact:true}).click();};
try {
 const cid=await h.create();await h.send(cid,'查2026年1月净收入');await h.finished(cid);
 const original=(await list(cid)).queries[0];assert.equal(original.execution_state,'not_submitted');
 await page.goto(h.url);await page.getByLabel('演示登录凭据').fill(h.tokens.alice);await page.getByRole('button',{name:'进入工作台 →'}).click();
 await page.getByRole('navigation',{name:'会话历史'}).getByRole('button',{name:/查2026年1月净收入/}).click();
 await page.locator('.messages .query-card').waitFor();
 assert.ok(!(await page.locator('.conversation').innerText()).includes(original.task_id));
 assert.equal(await page.getByText(/本次对话中的问题/).count(),0);
 assert.equal(await page.getByRole('button',{name:/继续这个问题|停止这个问题的分析|取消这个问题|补充或纠正|执行查询|取消查询|查看结果/}).count(),0);
 await h.pauseWorker();await send('仅看app渠道');
 await until(async()=>(await list(cid)).confirmation_blocked,'新消息暂停确认');
 const attempted=await h.request('/queries/'+original.id+'/confirm',{operation_id:randomUUID(),draft_version:original.draft_version,condition_version:original.condition_version});assert.equal(attempted.value.code,'message_pending');
 await h.resumeWorker();await h.finished(cid,2);
 await page.getByText('此前的 SQL · 已被修改',{exact:true}).waitFor();
 const revised=(await list(cid)).queries.find(q=>q.id!==original.id);assert.equal(revised.parameters.channel,'app');assert.equal(revised.execution_state,'not_submitted');assert.equal(revised.task_id,original.task_id);
 const card=page.locator('.query-card:not(.superseded)').last();
 await card.getByRole('button',{name:'复制 SQL',exact:true}).click();
 const copied=await page.evaluate(()=>navigator.clipboard.readText());assert.ok(copied.startsWith(revised.sql));assert.match(copied,/绑定参数/);
 for(const value of Object.values(revised.parameters))assert.ok(copied.includes(String(value)));
 await send('执行上面这条');
 await until(async()=>(await h.request('/queries/'+revised.id)).value.execution_state==='succeeded','聊天执行完成');
 await page.locator('.result-panel table').waitFor();assert.match(await page.locator('.result-panel').innerText(),/1600/);
 await h.finished(cid,4);
 assert.equal(await card.locator('pre').innerText(),revised.sql);await card.getByText('实际执行的 SQL',{exact:true}).waitFor();
 const ordering=await page.locator('.messages > .message').allInnerTexts();assert.ok(ordering.findIndex(t=>t.includes('实际执行的 SQL'))>ordering.findIndex(t=>t.trim().endsWith('执行上面这条')));
 const visible=await page.locator('.conversation').innerText();assert.ok(!visible.includes(original.task_id));assert.doesNotMatch(visible,/草稿版本\s*\d|条件版本\s*\d|SQL 版本/);
 checks.push('自然补充只改SQL；消息未归属时服务端暂停确认；聊天明确执行后自动显示独立参考1600分及实际SQL，SQL/参数可一起复制');
 await send('改成2月，再执行');await h.finished(cid,5);
 const february=(await list(cid)).queries.find(q=>q.id!==original.id&&q.id!==revised.id);assert.ok(february);assert.equal(february.parameters.start,'2026-02-01T00:00:00Z');assert.equal(february.parameters.channel,'app');
 await until(async()=>(await h.request('/queries/'+february.id)).value.execution_state==='succeeded','修改后直接执行');await h.finished(cid,6);
 await until(async()=>await page.locator('.result-panel table').count()===2,'两次执行结果各自展示');
 assert.equal(await card.locator('pre').innerText(),february.sql);assert.match(await card.getByLabel('绑定参数').innerText(),/2026-02-01/);
 checks.push('修改月份并要求执行，同条消息执行最终修订；已运行旧查询和新查询各保留实际SQL与结果');
 await page.getByLabel('你的数据问题').fill('保留的追问草稿');await page.reload();
 await until(async()=>await page.getByLabel('你的数据问题').inputValue()==='保留的追问草稿','草稿恢复');assert.equal(await page.locator('.composer-subject').count(),0);
 await until(async()=>await page.locator('.result-panel table').count()===2,'刷新后结果自动恢复');
 checks.push('普通追问草稿刷新后保留，不需要选择任务或SQL引用');
 for(const width of [1440,390]){await page.setViewportSize({width,height:1000});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));await page.screenshot({path:directory+'/workbench-'+width+'.png',fullPage:true,animations:'disabled'});}
 await page.setViewportSize({width:1440,height:1000});await send('查2026年1月支付客户数');await h.finished(cid,7);
 const waiting=(await list(cid)).queries.find(q=>q.task_id!==original.task_id);assert.ok(waiting);assert.equal(waiting.execution_state,'not_submitted');
 await send('执行这条');await page.getByRole('button',{name:'停止',exact:true}).click();
 await until(async()=>(await h.request('/queries/'+waiting.id)).value.execution_state==='cancelled','运行查询停止');
 assert.equal((await h.snapshot(cid)).tasks.find(t=>t.id===waiting.task_id).lifecycle,'active');
 checks.push('运行中保留停止入口，平台核对取消结果，继续保留对话和分析任务');
 assert.deepEqual(errors,[]);passed=true;
} finally {if(!passed)await page.screenshot({path:directory+'/failure.png',fullPage:true}).catch(()=>{});await writeFile(directory+'/report.json',JSON.stringify({passed,checks,errors,officialRequests:0},null,2));await browser.close();await h.close();console.log(JSON.stringify({passed,checks,errors,officialRequests:0}));}
