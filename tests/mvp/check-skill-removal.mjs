  pending(await select(failedHarness, failedCid, failedSkill));
  assert.equal((await failedSelections()).change_blocked, true);
  assert.equal((await failedHarness.request(`/conversations/${failedCid}/messages/${failedMessage.message_id}/withdraw`, { operation_id: randomUUID() })).value.code, 'input_already_applied');
